async fn original_consumption(pool: &PgPool) -> Settlement {
    let (_, _, _, _, order) = crate::payment_test_fixture::accepted(pool).await;
    for code in ["SEAT-COVER", "SEAT-FOAM"] {
        crate::stock::warehouse_movement(
            pool,
            crate::stock::WarehouseRequest {
                effect_key: code,
                component_code: code,
                change: commerce_domain::inventory::WarehouseChange::Receive(4),
                actor: "fixture-warehouse",
                reason: "literal spare physical backing",
            },
        )
        .await
        .expect("genuine physical receiving");
    }
    let mut tx = pool.begin().await.expect("original source manifest");
    let original = crate::order_stock::source::members(&mut tx, &order, true)
        .await
        .expect("genuinely accepted complete reservation");
    tx.rollback().await.expect("rollback source read");
    crate::holds::transition_hold(
        pool,
        &original.members[0].hold_id,
        crate::holds::HoldCommand::Consume {
            owner_id: &order.identity.id,
            actor_id: "payment-settlement",
        },
        1500,
    )
    .await
    .expect("genuine canonical member consumption");
    Settlement {
        id: "1".repeat(32),
        order_id: order.identity.id,
        attempt_id: "2".repeat(32),
        recognition_id: "3".repeat(32),
        group_id: order.identity.stock_group_id,
        actor: "payment-settlement".into(),
        settled_at: 1500,
        footprint: Footprint {
            schema_version: 1,
            members: original.members,
            components: vec![
                Component {
                    component_code: "SEAT-COVER".into(),
                    quantity: 6,
                    before: Balance {
                        on_hand: 10,
                        quarantine: 0,
                        reserved: 6,
                    },
                    after: Balance {
                        on_hand: 4,
                        quarantine: 0,
                        reserved: 0,
                    },
                },
                Component {
                    component_code: "SEAT-FOAM".into(),
                    quantity: 6,
                    before: Balance {
                        on_hand: 10,
                        quarantine: 0,
                        reserved: 6,
                    },
                    after: Balance {
                        on_hand: 4,
                        quarantine: 0,
                        reserved: 0,
                    },
                },
            ],
        },
    }
}
async fn healthy(pool: &PgPool, s: &Settlement) {
    let mut tx = pool.begin().await.expect("paired original movement proof");
    source(
        &mut tx,
        &s.footprint.members,
        &["consumed".into()],
        &s.order_id,
    )
    .await
    .expect("original reserve and terminal custody");
    settled(&mut tx, s)
        .await
        .expect("original literal intermediate balances and chronology");
    tx.rollback().await.expect("rollback proof read");
}
#[sqlx::test(migrator = "MIGRATOR")]
async fn terminal_proof_independently_checks_reserve_order_member_order_and_intermediate_quarantine_and_reserved(
    pool: PgPool,
) {
    let s = original_consumption(&pool).await;
    healthy(&pool, &s).await;
    let sequence:Vec<(String,i64)>=sqlx::query_as("SELECT component_code,sequence FROM stock_movements WHERE action='consume-hold' ORDER BY sequence").fetch_all(&pool).await.expect("literal canonical movement chronology");
    assert_eq!(
        sequence,
        vec![("SEAT-COVER".into(), 5), ("SEAT-FOAM".into(), 6)]
    );
    let mut tx = pool.begin().await.expect("reserve ordering damage");
    tx.execute("ALTER TABLE stock_movements DISABLE TRIGGER USER; ALTER TABLE stock_movements ALTER COLUMN sequence SET GENERATED BY DEFAULT; UPDATE stock_movements SET sequence=100 WHERE action='reserve' AND component_code='SEAT-COVER'").await.expect("controlled positive sequence after terminal");
    assert_eq!(
        source(
            &mut tx,
            &s.footprint.members,
            &["consumed".into()],
            &s.order_id
        )
        .await
        .err(),
        Some(SettlementError::InvalidStoredData)
    );
    tx.rollback().await.expect("exact identity/rows restored");
    healthy(&pool, &s).await;
    for sql in [
        "ALTER TABLE stock_movements ALTER COLUMN sequence SET GENERATED BY DEFAULT; UPDATE stock_movements SET sequence=100 WHERE action='consume-hold' AND component_code='SEAT-COVER'; UPDATE stock_movements SET sequence=5 WHERE action='consume-hold' AND component_code='SEAT-FOAM'; UPDATE stock_movements SET sequence=6 WHERE action='consume-hold' AND component_code='SEAT-COVER'",
        "UPDATE stock_movements SET quarantine_after=1 WHERE action='consume-hold' AND component_code='SEAT-COVER'",
        "UPDATE stock_movements SET reserved_after=1 WHERE action='consume-hold' AND component_code='SEAT-COVER'",
    ] {
        let mut tx = pool
            .begin()
            .await
            .expect("independent intermediate movement damage");
        tx.execute("ALTER TABLE stock_movements DISABLE TRIGGER USER")
            .await
            .expect("isolated immutable source fixture");
        tx.execute(sql)
            .await
            .expect("basic valid movement shape with wrong chronology/parity");
        assert_eq!(
            settled(&mut tx, &s).await.err(),
            Some(SettlementError::InvalidStoredData),
            "exact member proof: {sql}"
        );
        tx.rollback().await.expect("exact source/schema repair");
        healthy(&pool, &s).await;
    }
}
#[sqlx::test(migrator = "MIGRATOR")]
async fn movement_reader_rejects_more_than_2560_rows_before_imported_extra_effects_can_hide_past_its_bound(
    pool: PgPool,
) {
    let s = original_consumption(&pool).await;
    let mut tx = pool.begin().await.expect("bounded healthy movement reader");
    assert_eq!(
        movements(&mut tx, &s.footprint.members)
            .await
            .expect("literal complete source")
            .len(),
        4
    );
    tx.rollback().await.expect("rollback");
    let mut tx = pool
        .begin()
        .await
        .expect("controlled excessive imported movement set");
    tx.execute("ALTER TABLE physical_components DISABLE TRIGGER USER; ALTER TABLE stock_movements DISABLE TRIGGER USER; INSERT INTO physical_components(code,kind) SELECT 'DEMO-EXTRA-'||lpad(n::text,4,'0'),'cover' FROM generate_series(1,1280) n").await.expect("basic valid extra component identities");
    sqlx::query("INSERT INTO stock_movements(effect_key,component_code,action,quantity,actor,reason,on_hand_delta,quarantine_delta,reserved_delta,on_hand_after,quarantine_after,reserved_after,hold_id) SELECT 'hold:'||$1||':reserve:'||code,code,'reserve',1,$2,'sealed BOM hold transition',0,0,1,1,0,1,$1 FROM physical_components WHERE code LIKE 'DEMO-EXTRA-%'").bind(&s.footprint.members[0].hold_id).bind(&s.order_id).execute(&mut *tx).await.expect("1280 positive reserve-shaped rows");
    sqlx::query("INSERT INTO stock_movements(effect_key,component_code,action,quantity,actor,reason,on_hand_delta,quarantine_delta,reserved_delta,on_hand_after,quarantine_after,reserved_after,hold_id) SELECT 'hold:'||$1||':consume-hold:'||code,code,'consume-hold',1,'payment-settlement','sealed BOM hold transition',-1,0,-1,0,0,0,$1 FROM physical_components WHERE code LIKE 'DEMO-EXTRA-%'").bind(&s.footprint.members[0].hold_id).execute(&mut *tx).await.expect("1280 positive consume-shaped rows");
    let rows: i64 = sqlx::query_scalar("SELECT count(*) FROM stock_movements WHERE hold_id=$1")
        .bind(&s.footprint.members[0].hold_id)
        .fetch_one(&mut *tx)
        .await
        .expect("excess instrument positive control");
    assert_eq!(rows, 2564);
    assert_eq!(
        movements(&mut tx, &s.footprint.members).await.err(),
        Some(SettlementError::InvalidStoredData)
    );
    tx.rollback()
        .await
        .expect("restore all exact original rows and native schema");
    healthy(&pool, &s).await;
}
